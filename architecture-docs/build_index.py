"""
Build Index Utility - architecture-docs Skill
Regenerates the generated sections of the index (TECDOC.md): the subsystem map and
the ADR list. Only the text between the architecture-docs markers is replaced;
everything else in the index is hand-written and left untouched. Creates the index
from a template when it does not exist.
"""
import argparse
import os
import re
import sys

from _docs import MARKER, Project, adr_label, as_id_list, setup_stdout

INDEX_TEMPLATE = """# {name} — Technical Documentation

Entry point to the architecture of {name}. This index is maintained with the
`architecture-docs` skill: the sections between `architecture-docs` markers are
generated by `build_index.py`; the rest is written by hand.

## System Overview

Describe the system in a few paragraphs and one diagram: main components, how a
request flows through them, and where state lives.

## Subsystems

{subsystems}

## Architecture Decision Records

{adrs}

## How to Update This Documentation

- **A subsystem changed** (behavior, structure, data): edit its page in `{architecture_dir}/` in place, replacing outdated text.
- **A decision with alternatives and trade-offs**: create an ADR with `new_adr.py` and link it from the subsystem page.
- **A decision that reverses or corrects another**: create a new ADR with `--supersedes` or `--amends`; never rewrite an accepted ADR.
- **A feature was removed**: remove it from the subsystem page; its ADRs stay as history.
- **A release**: nothing here; release notes live in the GitHub releases.
- Run `check_docs.py` before committing.
"""


def block(name: str, content: str) -> str:
    return f"{MARKER.format(name=name, edge='start')}\n{content}\n{MARKER.format(name=name, edge='end')}"


def first_paragraph(body: str) -> str:
    for chunk in re.split(r"\n\s*\n", body):
        text = chunk.strip()
        if text and not text.startswith(("#", "<!--", "```", "|", ">", "-", "*")):
            text = " ".join(text.split())
            return text if len(text) <= 160 else text[:157].rstrip() + "..."
    return ""


def render_subsystems(project: Project) -> str:
    docs = project.architecture_docs()
    if not docs:
        return f"_No subsystem pages yet. Create one with `new_subsystem.py`._"
    rows = ["| Subsystem | Summary |", "|---|---|"]
    for d in sorted(docs, key=lambda d: (d.meta.get("title") or d.h1 or "").lower()):
        title = d.meta.get("title") or d.h1 or os.path.basename(d.path)
        link = os.path.relpath(d.path, os.path.dirname(project.index_path)).replace(os.sep, "/")
        summary = (d.meta.get("summary") or first_paragraph(d.body)).replace("|", "\\|")
        rows.append(f"| [{title}]({link}) | {summary} |")
    return "\n".join(rows)


def render_adrs(project: Project) -> str:
    adrs = [a for a in project.adrs() if isinstance(a.meta.get("id"), int)]
    if not adrs:
        return "_No ADRs yet. Create one with `new_adr.py`._"
    rows = ["| ADR | Title | Status | Version | Date |", "|---|---|---|---|---|"]
    for a in sorted(adrs, key=lambda a: a.meta["id"], reverse=True):
        m = a.meta
        link = os.path.relpath(a.path, os.path.dirname(project.index_path)).replace(os.sep, "/")
        status = m.get("status", "")
        later = as_id_list(m.get("superseded_by"))
        if later:
            status += " by " + ", ".join(adr_label(i) for i in later)
        title = str(m.get("title", "")).replace("|", "\\|")
        rows.append(f"| [{adr_label(m['id'])}]({link}) | {title} | {status} | {m.get('version') or ''} | {m.get('date') or ''} |")
    return "\n".join(rows)


def render_index(project: Project) -> str:
    sections = {"subsystems": render_subsystems(project), "adrs": render_adrs(project)}
    if not os.path.isfile(project.index_path):
        return INDEX_TEMPLATE.format(
            name=project.name, architecture_dir=project.config["architecture_dir"].replace(os.sep, "/"),
            **{k: block(k, v) for k, v in sections.items()},
        )
    with open(project.index_path, "r", encoding="utf-8") as f:
        text = f.read()
    for name, content in sections.items():
        start, end = MARKER.format(name=name, edge="start"), MARKER.format(name=name, edge="end")
        pattern = re.compile(re.escape(start) + r".*?" + re.escape(end), re.S)
        if pattern.search(text):
            text = pattern.sub(lambda _: block(name, content), text)
        else:
            heading = "Subsystems" if name == "subsystems" else "Architecture Decision Records"
            text = text.rstrip() + f"\n\n## {heading}\n\n{block(name, content)}\n"
    return text


def build_index(project: Project, check: bool = False) -> bool:
    """Writes the index. With check=True only reports whether it is up to date."""
    new = render_index(project)
    old = None
    if os.path.isfile(project.index_path):
        with open(project.index_path, "r", encoding="utf-8") as f:
            old = f.read()
    if check:
        return old is not None and old.strip() == new.strip()
    if old is None or old.strip() != new.strip():
        with open(project.index_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(new.rstrip() + "\n")
        print(f"✅ Index updated: {project.rel(project.index_path)}")
    else:
        print(f"= Index already up to date: {project.rel(project.index_path)}")
    return True


if __name__ == "__main__":
    setup_stdout()
    parser = argparse.ArgumentParser(description="Regenerate the generated sections of the architecture index (TECDOC.md)")
    parser.add_argument("--dir", type=str, default=None, help="Project directory (default: current; the Git root is used)")
    parser.add_argument("--check", action="store_true", help="Only check whether the index is up to date (exit 1 if not)")
    args = parser.parse_args()

    project = Project(args.dir)
    if args.check:
        ok = build_index(project, check=True)
        print("✅ Index is up to date." if ok else "❌ Index is outdated: run build_index.py.")
        sys.exit(0 if ok else 1)
    build_index(project)
