//! `build_index.py`: the generated sections of the index (TECDOC.md), the subsystem map and
//! the ADR list, between the architecture-docs markers.

use std::sync::LazyLock;

use kernel::out::println;
use kernel::py::argparse::Parser;
use kernel::py::num::{is_space, strip};
use kernel::py::path::{SEP, basename, dirname, isfile, relpath};
use kernel::py::unicode::SPACE;
use kernel::py::{Crash, Value, lower as lower_text, read_text, write_text};
use regex::{NoExpand, Regex};

use crate::docs::{Project, adr_label, as_id_list, cmp_int, get, marker, no_attribute};

/// `INDEX_TEMPLATE.format(...)`.
fn index_template(name: &str, architecture_dir: &str, subsystems: &str, adrs: &str) -> String {
    format!(
        "# {name} — Technical Documentation

Entry point to the architecture of {name}. This index is maintained with the
`architecture-docs` skill: the sections between `architecture-docs` markers are
generated by `build_index.py`; the rest is written by hand.

## System Overview

Describe the system in a few paragraphs and one diagram: main components, how a
request flows through them, and where state lives.

## Subsystems

{subsystems}

## Architecture Decision Records

{adrs}

## How to Update This Documentation

- **A subsystem changed** (behavior, structure, data): edit its page in `{architecture_dir}/` in place, replacing outdated text.
- **A decision with alternatives and trade-offs**: create an ADR with `new_adr.py` and link it from the subsystem page.
- **A decision that reverses or corrects another**: create a new ADR with `--supersedes` or `--amends`; never rewrite an accepted ADR.
- **A feature was removed**: remove it from the subsystem page; its ADRs stay as history.
- **A release**: nothing here; release notes live in the GitHub releases.
- Run `check_docs.py` before committing.
"
    )
}

pub fn block(name: &str, content: &str) -> String {
    format!(
        "{}\n{content}\n{}",
        marker(name, "start"),
        marker(name, "end")
    )
}

/// The first prose paragraph of a page, collapsed to one line of at most 160 characters.
pub fn first_paragraph(body: &str) -> String {
    static PARAGRAPHS: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(&format!(r"\n[{SPACE}]*\n")).expect("valid pattern"));
    for chunk in PARAGRAPHS.split(body) {
        let text = strip(chunk);
        if !text.is_empty()
            && !["#", "<!--", "```", "|", ">", "-", "*"]
                .iter()
                .any(|p| text.starts_with(p))
        {
            let text = text
                .split(is_space)
                .filter(|w| !w.is_empty())
                .collect::<Vec<_>>()
                .join(" ");
            let n = text.chars().count();
            if n <= 160 {
                return text;
            }
            let cut: String = text.chars().take(157).collect();
            return format!("{}...", cut.trim_end_matches(is_space));
        }
    }
    String::new()
}

/// `str.lower()` on a value that must be a string.
fn lower(value: &Value) -> Result<String, Crash> {
    match value {
        Value::Str(s) => Ok(lower_text(s)),
        other => Err(no_attribute(other, "lower")),
    }
}

/// `str.replace("|", "\\|")` on a value that must be a string.
fn escape_pipes(value: &Value) -> Result<String, Crash> {
    match value {
        Value::Str(s) => Ok(s.replace('|', "\\|")),
        other => Err(no_attribute(other, "replace")),
    }
}

fn link(project: &Project, path: &str) -> Result<String, Crash> {
    Ok(relpath(path, &dirname(&project.index_path))?.replace(SEP, "/"))
}

pub fn render_subsystems(project: &Project) -> Result<String, Crash> {
    let docs = project.architecture_docs()?;
    if docs.is_empty() {
        return Ok("_No subsystem pages yet. Create one with `new_subsystem.py`._".into());
    }
    let mut keyed = Vec::new();
    for d in docs {
        let title = get(&d.meta, "title")?;
        let key = if title.truthy() {
            lower(title)?
        } else {
            lower_text(&d.h1().filter(|h| !h.is_empty()).unwrap_or_default())
        };
        keyed.push((key, d));
    }
    keyed.sort_by(|a, b| a.0.cmp(&b.0));
    let mut rows = vec![
        "| Subsystem | Summary |".to_string(),
        "|---|---|".to_string(),
    ];
    for (_, d) in keyed {
        let meta_title = get(&d.meta, "title")?;
        let title = if meta_title.truthy() {
            meta_title.py_str()
        } else {
            match d.h1().filter(|h| !h.is_empty()) {
                Some(h) => h,
                None => basename(std::path::Path::new(&d.path)),
            }
        };
        let link = link(project, &d.path)?;
        let summary = get(&d.meta, "summary")?;
        let summary = if summary.truthy() {
            escape_pipes(summary)?
        } else {
            first_paragraph(&d.body).replace('|', "\\|")
        };
        rows.push(format!("| [{title}]({link}) | {summary} |"));
    }
    Ok(rows.join("\n"))
}

/// An ADR id (`int`, or `bool` as Python allows) as an integer's decimal text.
fn id_text(value: &Value) -> Option<String> {
    match value {
        Value::Int(i) => Some(i.clone()),
        Value::Bool(b) => Some(if *b { "1" } else { "0" }.into()),
        _ => None,
    }
}

/// `status += text`.
fn add_str(status: Value, text: &str) -> Result<Value, Crash> {
    match status {
        Value::Str(s) => Ok(Value::Str(s + text)),
        Value::List(mut items) => {
            items.extend(text.chars().map(|c| Value::Str(c.to_string())));
            Ok(Value::List(items))
        }
        Value::Tuple(_) => Err(Crash::new(
            "TypeError: can only concatenate tuple (not \"str\") to tuple",
        )),
        Value::Bytes(_) => Err(Crash::new("TypeError: can't concat str to bytes")),
        other => Err(Crash::new(format!(
            "TypeError: unsupported operand type(s) for +=: '{}' and 'str'",
            other.type_name()
        ))),
    }
}

fn or_empty(value: &Value) -> String {
    if value.truthy() {
        value.py_str()
    } else {
        String::new()
    }
}

pub fn render_adrs(project: &Project) -> Result<String, Crash> {
    let mut adrs = Vec::new();
    for a in project.adrs()? {
        if let Some(id) = id_text(get(&a.meta, "id")?) {
            adrs.push((id, a));
        }
    }
    if adrs.is_empty() {
        return Ok("_No ADRs yet. Create one with `new_adr.py`._".into());
    }
    // sorted(..., reverse=True) keeps equal ids in their original order.
    adrs.sort_by(|a, b| cmp_int(&b.0, &a.0));
    let mut rows = vec![
        "| ADR | Title | Status | Version | Date |".to_string(),
        "|---|---|---|---|---|".to_string(),
    ];
    for (id, a) in adrs {
        let m = &a.meta;
        let link = link(project, &a.path)?;
        let mut status = match m {
            Value::Dict(d) => d.get("status").cloned().unwrap_or(Value::str("")),
            other => return Err(no_attribute(other, "get")),
        };
        let later = as_id_list(get(m, "superseded_by")?)?;
        if !later.is_empty() {
            let labels: Vec<String> = later.iter().map(|i| adr_label(i)).collect();
            status = add_str(status, &format!(" by {}", labels.join(", ")))?;
        }
        let title = match m {
            Value::Dict(d) => d.get("title").map_or(String::new(), Value::py_str),
            _ => String::new(),
        }
        .replace('|', "\\|");
        rows.push(format!(
            "| [{}]({link}) | {title} | {} | {} | {} |",
            adr_label(&id),
            status.py_str(),
            or_empty(get(m, "version")?),
            or_empty(get(m, "date")?)
        ));
    }
    Ok(rows.join("\n"))
}

pub fn render_index(project: &Project) -> Result<String, Crash> {
    let sections = [
        ("subsystems", render_subsystems(project)?),
        ("adrs", render_adrs(project)?),
    ];
    if !isfile(&project.index_path) {
        let architecture_dir = project
            .config
            .get("architecture_dir")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .replace(SEP, "/");
        return Ok(index_template(
            &project.name.py_str(),
            &architecture_dir,
            &block("subsystems", &sections[0].1),
            &block("adrs", &sections[1].1),
        ));
    }
    let mut text = read_text(std::path::Path::new(&project.index_path))?;
    for (name, content) in &sections {
        let pattern = Regex::new(&format!(
            "(?s){}.*?{}",
            regex::escape(&marker(name, "start")),
            regex::escape(&marker(name, "end"))
        ))
        .expect("valid pattern");
        let replacement = block(name, content);
        if pattern.is_match(&text) {
            text = pattern
                .replace_all(&text, NoExpand(&replacement))
                .into_owned();
        } else {
            let heading = if *name == "subsystems" {
                "Subsystems"
            } else {
                "Architecture Decision Records"
            };
            text = format!(
                "{}\n\n## {heading}\n\n{replacement}\n",
                text.trim_end_matches(is_space)
            );
        }
    }
    Ok(text)
}

/// `build_index(project, check)`: writes the index, or with `check` only reports whether it
/// is up to date.
pub fn build_index(project: &Project, check: bool) -> Result<bool, Crash> {
    let new = render_index(project)?;
    let index = std::path::Path::new(&project.index_path);
    let old = if isfile(&project.index_path) {
        Some(read_text(index)?)
    } else {
        None
    };
    if check {
        return Ok(old.is_some_and(|o| strip(&o) == strip(&new)));
    }
    let rel = |p: &Project| p.rel(&p.index_path);
    if old.as_deref().is_none_or(|o| strip(o) != strip(&new)) {
        write_text(index, &format!("{}\n", new.trim_end_matches(is_space)))?;
        println(&format!("✅ Index updated: {}", rel(project)?));
    } else {
        println(&format!("= Index already up to date: {}", rel(project)?));
    }
    Ok(true)
}

/// `python build_index.py [args]`.
pub fn main(argv: &[String]) -> u8 {
    match run(argv) {
        Ok(code) => code,
        Err(c) => c.report(),
    }
}

fn run(argv: &[String]) -> Result<u8, Crash> {
    let parser = Parser::new(
        "build_index.py",
        "Regenerate the generated sections of the architecture index (TECDOC.md)",
    )
    .option(
        "--dir",
        "Project directory (default: current; the Git root is used)",
    )
    .flag(
        "--check",
        "Only check whether the index is up to date (exit 1 if not)",
    );
    let args = match parser.parse(argv) {
        Ok(a) => a,
        Err(exit) => return Ok(exit.report()),
    };
    let project = Project::new(args.value("dir"))?;
    if args.flag("check") {
        let ok = build_index(&project, true)?;
        println(if ok {
            "✅ Index is up to date."
        } else {
            "❌ Index is outdated: run build_index.py."
        });
        return Ok(if ok { 0 } else { 1 });
    }
    build_index(&project, false)?;
    Ok(0)
}
